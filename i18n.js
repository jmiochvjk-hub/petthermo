  var BTN_SEL = '[data-lang-label]';
  function t(zh){
    if(LANG!=='ko'||zh==null) return zh;
    var s=String(zh), k=s.trim();
    if(k && KO[k]) return s.replace(k, function(){return KO[k];});
    return zh;
  }
  function collect(root){
    var w=document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {acceptNode:function(n){
      var p=n.parentNode; if(!p) return NodeFilter.FILTER_REJECT;
      var tag=p.nodeName;
      if(tag==='SCRIPT'||tag==='STYLE'||tag==='NOSCRIPT'||tag==='TEXTAREA') return NodeFilter.FILTER_REJECT;
      if(!n.nodeValue||!n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }});
    var out=[],n; while(n=w.nextNode()) out.push(n); return out;
  }
  function apply(lang){
    LANG = (lang==='ko')?'ko':'zh';
    var nodes=collect(document.body);
    for(var i=0;i<nodes.length;i++){
      var n=nodes[i], src;
      if(n.__t!=null && n.nodeValue===n.__t){ src=n.__zh; }
      else { src=n.nodeValue; n.__zh=src; }
      var key=src.trim();
      if(LANG==='ko' && key && KO[key]){
        var tr=src.replace(key, function(){return KO[key];});
        n.nodeValue=tr; n.__t=tr;
      } else { n.nodeValue=src; n.__t=null; }
    }
    document.documentElement.lang = (LANG==='ko')?'ko':'zh-CN';
    var btns=document.querySelectorAll(BTN_SEL);
    for(var j=0;j<btns.length;j++) btns[j].textContent=(LANG==='ko')?'中文':'한국어';
    try{ localStorage.setItem('petthermo-lang',LANG); }catch(e){}
    if(typeof window.onLangApplied==='function') window.onLangApplied(LANG);
  }
  function refresh(){ if(LANG==='ko') apply('ko'); }
  function toggle(){ apply(LANG==='ko'?'zh':'ko'); }
  function init(){
    var saved='zh';
    try{ saved=localStorage.getItem('petthermo-lang')||'zh'; }catch(e){}
    apply(saved);
  }
